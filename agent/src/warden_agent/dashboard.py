"""Render findings as a self-contained HTML dashboard.

One static HTML file, no external scripts or network calls, works in light and
dark. This is the artifact for the demo: open it in a browser and the findings
are right there, color-coded by severity with their framework mappings.
"""

from __future__ import annotations

import html
from collections import Counter

from .models import Finding, Severity

_SEV_ORDER = [Severity.CRITICAL, Severity.HIGH, Severity.MEDIUM, Severity.LOW]


def to_html(findings: list[Finding], title: str = "Warden findings") -> str:
    counts = Counter(f.severity for f in findings)
    tiles = "\n".join(_tile(sev, counts.get(sev, 0)) for sev in _SEV_ORDER)
    rows = "\n".join(_row(f) for f in findings) or (
        '<tr><td colspan="5" class="empty">No issues detected.</td></tr>'
    )
    safe_title = html.escape(title)
    return _TEMPLATE.format(title=safe_title, total=len(findings), tiles=tiles, rows=rows)


def _tile(sev: Severity, n: int) -> str:
    return (
        f'<div class="tile sev-{sev.value}">'
        f'<div class="tile-n">{n}</div>'
        f'<div class="tile-l">{sev.value.upper()}</div></div>'
    )


def _row(f: Finding) -> str:
    frameworks = ", ".join([*f.cis, *f.mitre]) or "-"
    return (
        "<tr>"
        f'<td><span class="badge sev-{f.severity.value}">{f.severity.value.upper()}</span></td>'
        f"<td>{html.escape(f.title)}</td>"
        f"<td><code>{html.escape(f.resource_id)}</code></td>"
        f"<td>{html.escape(frameworks)}</td>"
        f"<td>{html.escape(f.remediation_summary)}</td>"
        "</tr>"
    )


_TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>
  :root {{
    --bg: #f8fafc; --card: #ffffff; --text: #0f172a; --muted: #475569;
    --border: #e2e8f0; --code: #f1f5f9;
    --critical: #b91c1c; --high: #c2410c; --medium: #a16207; --low: #475569;
  }}
  @media (prefers-color-scheme: dark) {{
    :root {{
      --bg: #0b1120; --card: #111827; --text: #e5e7eb; --muted: #94a3b8;
      --border: #1f2937; --code: #0f172a;
      --critical: #ef4444; --high: #f97316; --medium: #eab308; --low: #94a3b8;
    }}
  }}
  * {{ box-sizing: border-box; }}
  body {{ margin: 0; background: var(--bg); color: var(--text);
    font: 15px/1.5 -apple-system, Segoe UI, Roboto, Helvetica, Arial, sans-serif; }}
  .wrap {{ max-width: 980px; margin: 0 auto; padding: 32px 16px; }}
  h1 {{ font-size: 22px; margin: 0 0 4px; }}
  .sub {{ color: var(--muted); margin: 0 0 24px; }}
  .tiles {{ display: flex; gap: 12px; flex-wrap: wrap; margin-bottom: 24px; }}
  .tile {{ flex: 1 1 120px; background: var(--card); border: 1px solid var(--border);
    border-radius: 10px; padding: 16px; border-left: 4px solid var(--border); }}
  .tile-n {{ font-size: 28px; font-weight: 700; }}
  .tile-l {{ color: var(--muted); font-size: 12px; letter-spacing: .05em; }}
  .tile.sev-critical {{ border-left-color: var(--critical); }}
  .tile.sev-high {{ border-left-color: var(--high); }}
  .tile.sev-medium {{ border-left-color: var(--medium); }}
  .tile.sev-low {{ border-left-color: var(--low); }}
  table {{ width: 100%; border-collapse: collapse; background: var(--card);
    border: 1px solid var(--border); border-radius: 10px; overflow: hidden; }}
  th, td {{ text-align: left; padding: 12px 14px; border-bottom: 1px solid var(--border);
    vertical-align: top; }}
  th {{ font-size: 12px; text-transform: uppercase; letter-spacing: .05em; color: var(--muted); }}
  tr:last-child td {{ border-bottom: none; }}
  code {{ background: var(--code); padding: 1px 6px; border-radius: 5px; font-size: 13px; }}
  .badge {{ display: inline-block; padding: 2px 8px; border-radius: 999px; color: #fff;
    font-size: 12px; font-weight: 600; }}
  .badge.sev-critical {{ background: var(--critical); }}
  .badge.sev-high {{ background: var(--high); }}
  .badge.sev-medium {{ background: var(--medium); }}
  .badge.sev-low {{ background: var(--low); }}
  .empty {{ text-align: center; color: var(--muted); padding: 28px; }}
  footer {{ color: var(--muted); font-size: 12px; margin-top: 20px; }}
</style>
</head>
<body>
  <div class="wrap">
    <h1>{title}</h1>
    <p class="sub">{total} finding(s) detected.</p>
    <div class="tiles">
{tiles}
    </div>
    <table>
      <thead>
        <tr><th>Severity</th><th>Finding</th><th>Resource</th><th>Frameworks</th><th>Fix</th></tr>
      </thead>
      <tbody>
{rows}
      </tbody>
    </table>
    <footer>Generated by Warden. Findings may contain real resource identifiers; keep this file private.</footer>
  </div>
</body>
</html>
"""
